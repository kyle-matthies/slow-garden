"use client";

import { useState } from "react";

const examples = [
  {
    label: "A question",
    title: "Room to think",
    earlier: "The kitchen table is always full. I keep moving my notebook from room to room.",
    later: "Cleared the end of the table today. Wrote there for the first time in weeks.",
    thread: "The notebook finally has a place to stay.",
  },
  {
    label: "A work idea",
    title: "A smaller first version",
    earlier: "What if we tried the workshop with one team before building the whole programme?",
    later: "The small session gave us a much better question to test next.",
    thread: "A small experiment became the start of a longer thought.",
  },
  {
    label: "A reading note",
    title: "Details worth keeping",
    earlier: "The essay pays attention to ordinary things: a chipped bowl, a bus stop, the light on a wall.",
    later: "Noticed the worn step outside the library. It reminded me of that essay.",
    thread: "Something from a book found its way into an ordinary day.",
  },
];

/** A local, illustrative interaction: no account, saved notes, or AI request. */
export function GardenExample() {
  const [selected, setSelected] = useState(0);
  const example = examples[selected];

  return (
    <section className="landing-example" aria-labelledby="example-heading">
      <p className="landing-example-caption" id="example-heading">An example, before you begin</p>
      <fieldset className="landing-example-options">
        <legend className="sr-only">Choose an example thought</legend>
        {examples.map((item, index) => (
          <button
            key={item.label}
            type="button"
            aria-pressed={selected === index}
            onClick={() => setSelected(index)}
          >{item.label}</button>
        ))}
      </fieldset>
      <div className="landing-notebook" aria-live="polite" aria-atomic="true">
        <h2>{example.title}</h2>
        <article>
          <h3>One day</h3>
          <p>{example.earlier}</p>
        </article>
        <article>
          <h3>Later, in the same thought</h3>
          <p>{example.later}</p>
        </article>
        <p className="landing-example-thread">{example.thread}</p>
      </div>
      <p className="landing-example-disclosure">Made-up writing to show how a thought can grow. Nothing here is saved or generated by AI.</p>
    </section>
  );
}
