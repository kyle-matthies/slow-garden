import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it } from "vitest";
import { GardenExample } from "./garden-example";

afterEach(cleanup);

it("lets a visitor explore use cases while keeping the example clearly separate from saved writing", () => {
  render(<GardenExample />);
  expect(screen.getByRole("button", { name: "A question" })).toHaveAttribute("aria-pressed", "true");
  expect(screen.getByRole("heading", { name: "What do I want from work?" })).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "A reading note" }));
  expect(screen.getByRole("button", { name: "A reading note" })).toHaveAttribute("aria-pressed", "true");
  expect(screen.getByRole("button", { name: "A question" })).toHaveAttribute("aria-pressed", "false");
  expect(screen.getByRole("heading", { name: "Details worth keeping" })).toBeInTheDocument();
  expect(screen.queryByRole("heading", { name: "What do I want from work?" })).not.toBeInTheDocument();
  expect(screen.getByText(/Nothing here is saved or generated by AI/)).toBeInTheDocument();
  expect(screen.getByText("Made-up example")).toBeInTheDocument();
});

it("shows a bloom that quotes both of the person's lines and is marked as AI-derived", () => {
  render(<GardenExample />);
  const bloom = screen.getByRole("article", { name: "Example bloom" });
  expect(bloom).toHaveTextContent("AI-derived");
  expect(bloom).toHaveTextContent("I keep saying I want a quieter job, then I volunteer for the loudest project.");
  expect(bloom).toHaveTextContent("Best hour this week: the one where nobody needed me.");
  expect(bloom.querySelectorAll("blockquote")).toHaveLength(2);
});
