import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it } from "vitest";
import { GardenExample } from "./garden-example";

afterEach(cleanup);

it("lets a visitor explore use cases while keeping the example clearly separate from saved writing", () => {
  render(<GardenExample />);
  expect(screen.getByRole("button", { name: "A question" })).toHaveAttribute("aria-pressed", "true");
  expect(screen.getByRole("heading", { name: "Room to think" })).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "A reading note" }));
  expect(screen.getByRole("button", { name: "A reading note" })).toHaveAttribute("aria-pressed", "true");
  expect(screen.getByRole("button", { name: "A question" })).toHaveAttribute("aria-pressed", "false");
  expect(screen.getByRole("heading", { name: "Details worth keeping" })).toBeInTheDocument();
  expect(screen.queryByRole("heading", { name: "Room to think" })).not.toBeInTheDocument();
  expect(screen.getByText(/Nothing here is saved or generated by AI/)).toBeInTheDocument();
});
